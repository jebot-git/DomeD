#!/usr/bin/env python3
"""Embed editable Inkscape SVG flags for the shell and native input frontend."""
from pathlib import Path
import xml.etree.ElementTree as ET
ROOT=Path(__file__).resolve().parents[1]
lines=['// SPDX-License-Identifier: MIT','// Generated by scripts/embed-keyboard-flags.py; edit native/icons/flags/*.svg.','#pragma once','#include <algorithm>','#include <string>','namespace dx_flags {','inline std::string svg(const std::string &country, const std::string &border = "#80aabd") {','  std::string source;']
for path in sorted((ROOT/'native/icons/flags').glob('*.svg')):
    # Keep the SVG namespace default so FLTK's SVG parser can read the result.
    ET.register_namespace('', 'http://www.w3.org/2000/svg')
    source=ET.tostring(ET.parse(path).getroot(),encoding='unicode').replace('\n','')
    lines.append(f'  if (country == "{path.stem}") source = R"SVG({source})SVG";')
lines+=['  if (source.empty()) return svg("generic", border);','  auto at = source.rfind("#80aabd");','  if (at != std::string::npos) source.replace(at, 7, border);','  return source;','}', '''inline std::string country(std::string method, std::string language = "") {
  std::transform(method.begin(), method.end(), method.begin(), ::tolower);
  if (method == "anthy" || method.find("mozc") != std::string::npos) return "jp";
  if (method == "hangul") return "kr";
  if (method.rfind("keyboard-", 0) == 0) method = method.substr(9);
  method = method.substr(0, method.find('-'));
  for (const auto *country : {"us", "gb", "jp", "cz", "kr", "rs", "de", "fr"})
    if (method == country) return country;
  language = language.substr(0, language.find_first_of("_-"));
  if (language == "ja") return "jp";
  if (language == "ko") return "kr";
  if (language == "cs") return "cz";
  if (language == "sr") return "rs";
  if (language == "de" || language == "fr") return language;
  return "generic";
}''','} // namespace dx_flags']
(ROOT/'native/keyboard-flags.h').write_text('\n'.join(lines)+'\n')
